--PART – C:
--9. CREATE A STORED PROCEDURE WHICH DISPLAYS DEPARTMENT-WISE MAXIMUM, MINIMUM, AND AVERAGE SALARY OF
--EMPLOYEE.

CREATE PROCEDURE PR_MAX_MIN_AVG_SALARY
AS
BEGIN
	SELECT DEPARTMENT , MAX(SALARY) AS MAX_SALARY , MIN(SALARY) AS MIN_SALARY , AVG(SALARY) AS AVG_SALARY FROM EMPLOYEE
	GROUP BY DEPARTMENT
END

EXEC PR_MAX_MIN_AVG_SALARY


--10. CREATE A STORED PROCEDURE THAT ACCEPTS DEPARTMENT NAME AS PARAMETER AND RETURNS TOTAL SALARY OF THEIR
--DEPARTMENT. 

CREATE PROCEDURE PR_DEPARTEMENT_WISE_TOTAL_SALARY
@DEPARTMENT VARCHAR(30)
AS
BEGIN
	SELECT DEPARTMENT , SUM(SALARY) AS TOTAL_SALARY FROM EMPLOYEE
	WHERE DEPARTMENT = @DEPARTMENT
	GROUP BY DEPARTMENT

END

EXEC PR_DEPARTEMENT_WISE_TOTAL_SALARY 'HR'


