--3.UPDATE PROCEDURES: CREATE STORED PROCEDURE SP_UPDATE_STUDENT TO UPDATE BRANCH IN STUDENT
--TABLE. (UPDATE USING STUDENTID) 

	--STDID	BRANCH	
	--115		ELECTRICAL
	--116		MECHANICAL 

CREATE PROCEDURE PR_UPDATE_STUDENT
 @STDID INT ,
 @BRANCH VARCHAR(30)
 AS 
 BEGIN
	UPDATE STUDENT
	SET BRANCH = @BRANCH
	WHERE STDID = @STDID
 END

 EXEC PR_UPDATE_STUDENT @STDID = 115 , @BRANCH = 'ELECTRICAL'
 EXEC PR_UPDATE_STUDENT @STDID = 116 , @BRANCH = 'MECHANICAL'

 SELECT * FROM STUDENT

