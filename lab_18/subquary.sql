		SELECT R.SPI FROM RESULT R
		INNER JOIN STUDENT_INFO S1
		ON S1.RNO = R.RNO
		WHERE S1.BRNACH = 'CE'
	)
--25. DISPLAY THE BRANCH THAT CONTAINS THE STUDENT WITH HIGHEST SPI.
	
	SELECT *
	FROM STUDENT_INFO S
	INNER JOIN RESULT R
	ON R.RNO = S.RNO
	WHERE R.SPI >= ALL(
		SELECT MAX(R.SPI) FROM RESULT R
		INNER JOIN STUDENT_INFO S1
		ON S1.RNO = R.RNO
		GROUP BY S1.BRNACH
	)
--26. DISPLAY THE STUDENTS WHOSE SPI IS LESS THAN THE SPI OF EVERY STUDENT IN CE BRANCH AND GREATER THAN EVERY 
--STUDENT IN ME BRANCH.
SELECT *
FROM STUDENT_INFO S
INNER JOIN RESULT R
    ON R.RNO = S.RNO
WHERE R.SPI < ALL (
    SELECT R1.SPI
    FROM RESULT R1
    INNER JOIN STUDENT_INFO S1
        ON S1.RNO = R1.RNO
    WHERE S1.BRNACH = 'CE'
)
AND R.SPI > ALL (
    SELECT R2.SPI
    FROM RESULT R2
    INNER JOIN STUDENT_INFO S2
        ON S2.RNO = R2.RNO
    WHERE S2.BRNACH = 'ME'
);

