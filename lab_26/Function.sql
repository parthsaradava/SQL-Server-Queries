--14. CREATE A TABLE VALUED FUNCTION THAT ACCEPTS STDID AND RETURNS STUDENT RANK BASED ON SPI (RANK). 
CREATE OR ALTER FUNCTION STUDENT_RANK(
	@STDID INT
)
RETURNS TABLE
AS
	RETURN SELECT * FROM 
	(	
		SELECT STDID , SNAME , CITY , SPI , BRANCH , 
		RANK() OVER(ORDER BY SPI DESC) AS STUDENTRANK
		FROM STUDENT
	)
	AS S
	WHERE STDID = @STDID
	

SELECT * FROM STUDENT_RANK(101)


--15. CREATE A TABLE VALUED FUNCTION THAT ACCEPTS BRANCH AND RETURNS STUDENTS HAVING SECOND HIGHEST SPI 
--FROM THAT BRANCH.

CREATE OR ALTER FUNCTION STUDENT_BRANCH(
	@BRANCH VARCHAR(30)
)
RETURNS TABLE
AS
	RETURN SELECT * FROM 
	(	
		SELECT STDID , SNAME , CITY , SPI , BRANCH , 
		DENSE_RANK() OVER(ORDER BY SPI DESC) AS STUDENTRANK
		FROM STUDENT
		WHERE BRANCH = @BRANCH
	)
	AS S
	WHERE STUDENTRANK = 2
	

SELECT * FROM STUDENT_BRANCH('COMPUTER')
