--2. CREATE A TABLE VALUED FUNCTION THAT ACCEPTS CITY AND RETURNS ALL STUDENTS FROM THAT CITY. 

CREATE OR ALTER FUNCTION STUDENT_CITY(
	@CITY VARCHAR(30)
)
RETURNS TABLE
