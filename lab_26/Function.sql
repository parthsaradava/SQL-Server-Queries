--9. CREATE A TABLE VALUED FUNCTION THAT ACCEPTS TOPN AND RETURNS TOP N STUDENTS BASED ON SPI.

CREATE OR ALTER FUNCTION STD_TOPN(
	@TOPN INT
)
RETURNS TABLE
AS
	RETURN SELECT TOP (@TOPN) * FROM STUDENT
	ORDER BY SPI DESC
	

SELECT * FROM STD_TOPN(3)
