--5. CREATE A STORED PROCEDURE TO DISPLAY TOP N HIGHEST PAID EMPLOYEES FROM EACH DEPARTMENT (VALUE OF N
--IS ENTERED BY USER).
CREATE OR ALTER PROCEDURE PR_TOP_N_HIGEST_PAID_EMPLOYEE
	@N INT
AS
BEGIN
	SELECT * 
	FROM(
		SELECT * , ROW_NUMBER() OVER(PARTITION BY DEPARTMENT 
									 ORDER BY SALARY DESC) AS ORDER_RANK
		FROM EMPLOYEE
		) AS T
		WHERE ORDER_RANK <= @N 
END
EXEC PR_TOP_N_HIGEST_PAID_EMPLOYEE 2
--6. CREATE A STORED PROCEDURE TO INCREASE SALARY DEPARTMENT-WISE BY A GIVEN PERCENTAGE. (USER ENTER
--DEPARTMENT NAME AND %, E.G. COMPUTER 10).

CREATE OR ALTER PROCEDURE PR_INCREASE_SALARY
	@DNAME VARCHAR(30) ,
	@INCREMENT DECIMAL(5,2)
AS
BEGIN
	UPDATE EMPLOYEE
	SET SALARY = SALARY + (SALARY * @INCREMENT / 100)
	WHERE DEPARTMENT = @DNAME
END

