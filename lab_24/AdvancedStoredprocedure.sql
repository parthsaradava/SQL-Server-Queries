--9. CREATE A STORED PROCEDURE THAT ACCEPTS AN AUTHOR NAME AND DISPLAYS ALL BOOKS WRITTEN BY THAT AUTHOR.

CREATE OR ALTER PROCEDURE PR_AUTHONNAME_BOOK
	@NAME VARCHAR(30)
AS
BEGIN
	SELECT A.AUTHORNAME , A.COUNTRY , B.TITLE 
	FROM AUTHOR A
	INNER JOIN BOOK B
	ON B.AUTHORID = A.AUTHORID
	WHERE A.AUTHORNAME = @NAME
END

EXEC PR_AUTHONNAME_BOOK 'CHETAN BHAGAT'
