--12. CREATE A STORED PROCEDURE THAT ACCEPTS A NUMBER AS INPUT AND DISPLAYS THE TOP N MOST EXPENSIVE BOOKS
--WITH AUTHOR AND PUBLISHER DETAILS.
CREATE OR ALTER PROCEDURE PR_EXPENSIVE_BOOK
	@N INT 
AS
BEGIN
	SELECT TOP (@N) A.AUTHORNAME , B.PRICE , P.PUBLISHERNAME
	FROM AUTHOR A
	INNER JOIN BOOK B
	ON A.AUTHORID = B.AUTHORID
	INNER JOIN PUBLISHER P
	ON P.PUBLISHERID = B.PUBLISHERID
	ORDER BY B.PRICE DESC
END

EXEC PR_EXPENSIVE_BOOK 3


