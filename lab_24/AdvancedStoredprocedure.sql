--13. CREATE A STORED PROCEDURE THAT ACCEPTS A PUBLISHER NAME AND DISPLAYS THE TOTAL NUMBER OF BOOKS
--PUBLISHED BY THAT PUBLISHER.
CREATE OR ALTER PROCEDURE PR_PUBLISHERNAME
	@NAME VARCHAR(30) , @COUNT INT OUTPUT
AS
BEGIN
	SELECT COUNT(B.BOOKID) AS TOTAL_BOOKS
	FROM BOOK B
	INNER JOIN PUBLISHER P
	ON P.PUBLISHERID = B.PUBLISHERID
	WHERE P.PUBLISHERNAME = @NAME
END

